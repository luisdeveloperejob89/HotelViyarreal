    public boolean HabitacionValida(int iIdHabitacion)
    {
        boolean bOk = false;
        Habitacion hAux = new Habitacion();
        
        hAux.DameHabitacionInstanciada(iIdHabitacion);        
        bOk = ( hAux.getEstado() == 0 );
        
        return bOk;
    }
    
