    public void Reservar()
    {
        Date dtFechaActual = new Date();
        boolean bContinuar = true;
        
        if ( HuespedValido() )
        {
            if ( HabitacionValida(DameHabitacion()) )
            {
                if ( ( dtFecha.getDate() != null ) && ( dtFecha.getDate().getTime() > dtFechaActual.getTime() ) )
                {
                    if ( !ReservacionHabitacion.HabitacionReservada(DameHabitacion(), dtFecha.getDate()) )
                    {
                        if ( cboxHuespedNuevo.isSelected() )
                        {
                            AgregaCliente();
                            bContinuar = Cliente.Insertar();

                            if ( bContinuar )
                            {
                                this.IdHuesped = Cliente.getId();
                            }
                        }

                        if ( bContinuar )
                        {
                            if ( ReservacionHabitacion.Insertar(DameHabitacion(), IdHuesped, dtFecha.getDate()) )
                            {
                                uAccesibilidad.MuestraMensaje("Reservación generada correctamente.");
                                this.dispose();
                            }
                            else
                            {
                                uAccesibilidad.MuestraMensaje("Ha ocurrido un error al tratar de agregar la Reservación.");
                            }
                        }
                    }
                    else
                    {
                        uAccesibilidad.MuestraMensaje("La Habitación: " + DameHabitacion() + " ya se encuentra reservada para esa fecha.");
                    }
                }
                else
                {
                    uAccesibilidad.MuestraMensaje("No se puede dejar una fecha inválida.");
                }
            }
            else
            {
                uAccesibilidad.MuestraMensaje("La Habitación: " + DameHabitacion() + " no está disponible para ser reservada.");
            }
        }
        else
        {
            uAccesibilidad.MuestraMensaje("El Nombre y Apellido Paterno no pueden estar vacíos.");
        }        
    }
    
