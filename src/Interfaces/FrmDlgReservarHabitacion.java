    public void MuestraListaHuespedes()            
    {
        String strNombre = null;
        FrmListaHuespedes frm = new FrmListaHuespedes(null, true);
        
        frm.show();
        
        if ( frm.isPresionoAceptar() )
        {
            LimpiarCampos();
            this.IdHuesped = frm.getIdHuesped();
            strNombre = frm.getNombre() + " " + frm.getApPaterno() + " " + frm.getApMaterno();
            txtHuesped.setText(strNombre);
            txtNombre.setText(frm.getNombre());
            txtApPaterno.setText(frm.getApPaterno());
            txtApMaterno.setText(frm.getApMaterno());
            txtTelefono.setText(frm.getTelefono());
        }        
    }
    
    public void LimpiarCampos()
    {
        this.IdHuesped = 0;
        txtHuesped.setText(null);
        txtNombre.setText(null);
        txtApPaterno.setText(null);
        txtApMaterno.setText(null);
        txtTelefono.setText(null);
    }
    
