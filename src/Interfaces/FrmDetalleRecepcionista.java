    public void InstanciaUsuario()
    {
        if ( this.Agregar )
        {
            uUsuario.setNomUsuario(txtUsuario.getText());
            uUsuario.setContrasenia(txtContrasenia.getText());
            uUsuario.setNombre(txtNombre.getText());
            uUsuario.setApPaterno(txtApPaterno.getText());
            uUsuario.setApMaterno(txtApMaterno.getText());
            uUsuario.setTelefono(txtTelefono.getText());
            uUsuario.setEmail(txtEmail.getText());
            uUsuario.setDireccion(txtDireccion.getText());

            if ( rbtnRecepcionista.isSelected() )
            {
                uUsuario.setTipo(1);
            }
            else
            {
                uUsuario.setTipo(0);
            }
        }
        else
        {
            this.SentenciaSQLActualizacion = "UPDATE USUARIOS SET ";
            this.SentenciaSQLActualizacion += " USUARIO = '" + txtUsuario.getText() + "', ";
            this.SentenciaSQLActualizacion += " CONTRASENIA = '" + txtContrasenia.getText() + "', ";
            
            if ( rbtnRecepcionista.isSelected() )
            {
                this.SentenciaSQLActualizacion += " TIPO = 1, ";
            }
            else
            {
                this.SentenciaSQLActualizacion += " TIPO = 0, ";
            }
            
            this.SentenciaSQLActualizacion += " NOMBRE = '" + txtNombre.getText()+ "', ";
            this.SentenciaSQLActualizacion += " AP_PATERNO = '" + txtApPaterno.getText() + "', ";
            this.SentenciaSQLActualizacion += " AP_MATERNO = '" + txtApMaterno.getText() + "', ";
            this.SentenciaSQLActualizacion += " TELEFONO = '" + txtTelefono.getText() + "', ";
            this.SentenciaSQLActualizacion += " EMAIL = '" + txtEmail.getText() + "', ";
            this.SentenciaSQLActualizacion += " DIRECCION = '" + txtDireccion.getText() + "' ";
            this.SentenciaSQLActualizacion += " WHERE ID = " + this.IDUsuarioEdicion;
        }
    }
    
    public void LimpiaCampos()
    {
        txtUsuario.setText(null);
        txtContrasenia.setText(null);
        txtNombre.setText(null);
        txtApPaterno.setText(null);
        txtApMaterno.setText(null);
        txtTelefono.setText(null);
        txtEmail.setText(null);
        txtDireccion.setText(null);
        txtUsuario.requestFocus();
    }
    
    public void InsertarDatos()
    {
        if ( ValidaDatos() )
        {
            if ( ( this.Agregar ) ? ( !uUsuario.ExisteUsuario(txtUsuario.getText()) ) : true )
            {                
                InstanciaUsuario();
                
                if ( this.Agregar )
                {
                    if ( uUsuario.Insertar() )
                    {
                        uAccesibilidad.MuestraMensaje("Usuario agregado correctamente.");
                        LimpiaCampos();
                    }
                    else
                    {
                        uAccesibilidad.MuestraMensaje("Ocurrió un error al tratar de insertar al Usuario.");
                    }
                }
                else
                {
                    if ( uUsuario.Actualizar(this.SentenciaSQLActualizacion) )
                    {
                        uAccesibilidad.MuestraMensaje("Usuario editado correctamente.");
                        this.dispose();
                    }
                    else
                    {
                        uAccesibilidad.MuestraMensaje("Ocurrió un error al tratar de editar al Usuario.");
                    }
                }
            }
            else
            {
                ErrorUsuarioExistente();
            }
        }
        else
        {
            MuestraMensajeError();
        }
    }
    
    public void MuestraMensajeError()
    {
        if ( txtUsuario.getText().isEmpty() )
        {
            txtUsuario.requestFocus();
            txtUsuario.selectAll();
            uAccesibilidad.MuestraMensaje("El campo 'Usuario' no puede estar vacío.");
        }
        else if ( txtContrasenia.getText().isEmpty() )
        {
            txtContrasenia.requestFocus();
            txtContrasenia.selectAll();
            uAccesibilidad.MuestraMensaje("El campo 'Contraseña' no puede estar vacío.");
        }
        else if ( txtNombre.getText().isEmpty() ) 
        {
            txtNombre.requestFocus();
            txtNombre.selectAll();
            uAccesibilidad.MuestraMensaje("El campo 'Nombre' no puede estar vacío.");
        }
        else if ( txtApPaterno.getText().isEmpty() )
        {
            txtApPaterno.requestFocus();
            txtApPaterno.selectAll();
            uAccesibilidad.MuestraMensaje("El campo 'Apellido Paterno' no puede estar vacío.");
        }
        else if ( txtTelefono.getText().isEmpty() )
        {
            txtTelefono.requestFocus();
            txtTelefono.selectAll();
            uAccesibilidad.MuestraMensaje("El campo 'Teléfono' no puede estar vacío.");
        }
        else if ( txtDireccion.getText().isEmpty() )
        {
            txtDireccion.requestFocus();
            txtDireccion.selectAll();
            uAccesibilidad.MuestraMensaje("El campo 'Dirección' no puede estar vacío.");
        }         
    }
    
    public boolean ValidaDatos()            
    {
        boolean bOk = false;
        
        bOk = ( !txtUsuario.getText().isEmpty()  && !txtContrasenia.getText().isEmpty() &&
                !txtNombre.getText().isEmpty()   && !txtApPaterno.getText().isEmpty()   && 
                !txtTelefono.getText().isEmpty() && !txtDireccion.getText().isEmpty() );
        
        return bOk;
    }
    
