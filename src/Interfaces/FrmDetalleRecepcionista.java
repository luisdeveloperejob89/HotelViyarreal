    public void LlenaForma(int iID)
    {
        ResultSet rsResultado = null;
        
        try
        {
            rsResultado = uUsuario.DameInstanciaEdicionUsuario(iID);
            
            if ( rsResultado != null )
            {
                rsResultado.next();                
                txtUsuario.setText(rsResultado.getString("USUARIO"));
                txtUsuario.setEnabled(false);
                txtContrasenia.setText(rsResultado.getString("CONTRASENIA"));
                txtNombre.setText(rsResultado.getString("NOMBRE"));
                txtApPaterno.setText(rsResultado.getString("AP_PATERNO"));
                txtApMaterno.setText(rsResultado.getString("AP_MATERNO"));
                txtTelefono.setText(rsResultado.getString("TELEFONO"));
                txtEmail.setText(rsResultado.getString("EMAIL"));
                txtDireccion.setText(rsResultado.getString("DIRECCION"));
                
                if ( rsResultado.getInt("TIPO") == 0 )
                {
                    rbtnAdministrador.setSelected(true);
                }
                else
                {
                    rbtnRecepcionista.setSelected(true);
                }
            }
        }
        catch ( Exception e )
        {
            
        }
    }
    
