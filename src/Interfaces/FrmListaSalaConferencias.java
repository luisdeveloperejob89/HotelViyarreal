    public void GenerarAccion()
    {
        int iEstado = 0;
        
        iEstado = scSala.DameEstadoSalaDeConferencias();
        
        if ( iEstado == 0 )
        {
            ReservarSalaDeConferencias();
        }
        else if ( iEstado == 1 )
        {
            EntregarSalaConferencias();
        }
        else if ( iEstado == 3 || iEstado == 4 )
        {
            LiberarSalaConferencias();
        }
    }
    
    public void LiberarSalaConferencias()
    {
        if ( uAccesibilidad.MuestraMensajeConfirmacion("¿Deseas dejar Disponible la Sala de Conferencias?") == 0 )
        {
            if ( scSala.LiberaSalaDeConferencias())
            {
                uAccesibilidad.MuestraMensaje("Registro actualizado correctamente.");
                uAccesibilidad.RepintaFormasEnMenu(this.getParent());
            }
            else
            {
                uAccesibilidad.MuestraMensaje("Ocurrió un error al tratar de actualizar los Datos.");
            }
        }
    }
    
