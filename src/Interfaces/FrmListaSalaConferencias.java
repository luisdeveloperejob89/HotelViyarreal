    public void EnviarAMantenimientoSalaConferencias()
    {
        if ( uAccesibilidad.MuestraMensajeConfirmacion("¿Deseas enviar a la Sala de Conferencias a Mantenimiento?") == 0 )
        {
            if ( scSala.EnviarMantenimientoSalaConferencias() )
            {
                uAccesibilidad.MuestraMensaje("Registro actualizado correctamente.");
                uAccesibilidad.RepintaFormasEnMenu(this.getParent());
            }
            else
            {
                uAccesibilidad.MuestraMensaje("Ocurrió un error al tratar de actualizar los Datos.");
            }
        }
    }
    
