    private void txtDineroKeyReleased(java.awt.event.KeyEvent evt)//GEN-FIRST:event_txtDineroKeyReleased
    {//GEN-HEADEREND:event_txtDineroKeyReleased
        // TODO add your handling code here:
        double dCambio = 0.0;
        double dDineroIngresado = 0.0;
        
        try
        {
            dDineroIngresado = DameDineroIngresado();
            dCambio = ( dDineroIngresado > TotalPagar ) ? ( dDineroIngresado - TotalPagar ) : 0.0;
        }
        catch ( Exception e )
        {
            dCambio = 0.0;
        }
        
        txtCambio.setText(String.valueOf(dCambio));
    }//GEN-LAST:event_txtDineroKeyReleased

