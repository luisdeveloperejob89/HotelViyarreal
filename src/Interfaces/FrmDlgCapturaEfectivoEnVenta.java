    public double DameDineroIngresado()
    {        
        double dDineroIngresado = 0.0;
        
        try
        {
            dDineroIngresado = Double.parseDouble(txtDinero.getText());                     
        }
        catch ( Exception e )
        {
            dDineroIngresado = 0.0;
        }
        
        return dDineroIngresado;
    }
    
    public void ValidaDineroIngresado()
    {
        Utilerias uAccesibilidad = null;
        
        if ( ( !txtDinero.getText().isEmpty() ) && ( DameDineroIngresado() > 0.0 ) )
        {
            this.dispose();
        }
        else
        {
            uAccesibilidad = new Utilerias();
            uAccesibilidad.MuestraMensaje("Debes ingresar la cantidad con la cual te están pagando.");
            EnfocaDineroIngresado();
        }
    }
    
