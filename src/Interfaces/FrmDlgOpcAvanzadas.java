    public void RestaurarBDFabrica()
    {
        if ( uAccesibilidad.MuestraMensajeConfirmacion("¿Realmente deseas reestructurar toda la Base de datos a Fábrica?.") == 0 )
        {
            if ( opAvanzadas.RestauraBDOriginal() )
            {
                uAccesibilidad.MuestraMensaje("Base de datos reestructurada correctamente.\nEl Sistema se cerrará para poder aplicar la configuración.");
                System.exit(0);
            }
            else
            {
                uAccesibilidad.MuestraMensaje("Ocurrió un error al realizar el Proceso.");
            }
        }
    }
    
