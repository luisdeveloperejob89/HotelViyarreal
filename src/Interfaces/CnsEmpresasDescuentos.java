    public void EliminaEmpresaDescuento()
    {
        int iID = 0;
        String strNombreEmpresa = null;
        
        if ( uAccesibilidad.MuestraMensajeConfirmacion("¿Deseas realmente eliminar la Empresa seleccionada?") == 0 )
        {
            if ( tblClientes != null )
            {    
                iID = Integer.parseInt(tblClientes.getValueAt(tblClientes.getSelectedRow(), 0).toString());
                strNombreEmpresa = tblClientes.getValueAt(tblClientes.getSelectedRow(), 1).toString();
                EmpresasDescuento.setID(iID);
                
                if ( EmpresasDescuento.Eliminar() )
                {
                    uAccesibilidad.MuestraMensaje("Huesped eliminado correctamente.");
                    uBitacora.InsertarAccion(uUsuario.getID(), "EL USUARIO: " + uUsuario.getNomUsuario() + " ELIMINÓ EMPRESA: " +  strNombreEmpresa, "CONSULTA DE EMPRESAS", Bitacora.ELIMINAR_EMPRESADESCTO);
                    RefrescarForma();
                }
                else
                {
                    uAccesibilidad.MuestraMensaje("Ocurrió un error al tratar de eliminar al Huesped.");
                }
            }
        }
    }
    
