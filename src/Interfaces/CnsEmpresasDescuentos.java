    public void EditaEmpresaDescuento()
    {
        int iIDEmpresaAux = 0;
        FrmDetEmpresasDesctos frm = null;        
        
        try
        {
            if ( tblClientes != null )
            {    
                iIDEmpresaAux = Integer.parseInt(tblClientes.getValueAt(tblClientes.getSelectedRow(), 0).toString());
                frm = new FrmDetEmpresasDesctos(null, true, iIDEmpresaAux);        
                frm.show(true);
                RefrescarForma();            
            }
        }
        catch ( Exception e )
        {
            
        }
    }
    
