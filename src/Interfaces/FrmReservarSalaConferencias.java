    public void HabilitaDeshEmpresa(boolean bActivar)
    {
        labelNombreEmpresa.setEnabled(bActivar);
        btnEmpresas.setEnabled(bActivar);
        
        if ( !bActivar )
        {            
            txtEmpresa.setText(null);
            txtDescuento.setText("0");
            labelDescuento.setText("0 %");
            this.Descuento = 0.0;
            RecalculaTotalBoton(0);
        }        
    }
    
    public void RecalculaTotalBoton(int iOpcion)
    {
        int iTotalPersonas = 1;        
        double dPrecio = 0.0;        
        double dTotal = 0.0;        
        double dAnticipo = 0.0;
        double dDescuento = 0.0;
        double dPorcentajeDescuento = 0.0;
        
        if ( pPaquete != null )
        {
             if ( iOpcion == 0 )
             {
                if ( btnSoloSala.isSelected() )
                {
                    iOpcion = 1;
                }
                else if ( btnCoffee.isSelected() )
                {
                    iOpcion = 2;
                }
                else if ( btnAlmuerzo.isSelected() )
                {
                    iOpcion = 3;
                }               
             }
            
            switch ( iOpcion )
            {               
                case 1:
                    dPrecio = pPaquete.getPrecioSala();
                break;
                case 2:
                    dPrecio = pPaquete.getPrecioCoffee();
                break;
                case 3:                    
                    iTotalPersonas = Integer.parseInt(txtTotalPersonas.getText());
                    dPrecio = ( pPaquete.getPrecioAlmuerzoPP() * iTotalPersonas );
                break;
                default:
                    dPrecio = pPaquete.getPrecioSala();
            }
        }
        
        txtSubTotal.setText(String.valueOf(dPrecio));
        //dTotal = dPrecio * iTotalPersonas;
        dTotal = dPrecio;
        
        if ( cboxAnticipo.isSelected() )
        {
            dAnticipo = ( dTotal * CalculaAnticipo() ) / 100;
        }
        
        if ( cboxDescuentoEmpresas.isSelected() )
        {
            dPorcentajeDescuento = this.Descuento;
            dDescuento =  ( dTotal * dPorcentajeDescuento ) / 100;
            txtDescuento.setText(String.valueOf(dDescuento));
            dTotal -= dDescuento;
        }
        
        txtAnticipo.setText(String.valueOf(dAnticipo));
        txtTotal.setText(String.valueOf(dTotal));        
    }
    
    public void MuestraListaPaquetes()
    {
        pPaquete = null;
        FrmListaPaquetes frm = new FrmListaPaquetes(null, true);
        
        frm.show();
        pPaquete = frm.getpPaquete();
        txtPaquete.setText(pPaquete.getDescripcion());
        txtTiempoReservado.setText(String.valueOf(pPaquete.getHoras()));
        txtTotalPersonas.setText("30");
        txtPrecioSala.setText(String.valueOf(pPaquete.getPrecioSala()));
        txtPrecioCoffe.setText(String.valueOf(pPaquete.getPrecioCoffee()));
        txtPrecioPorPersona.setText(String.valueOf(pPaquete.getPrecioAlmuerzoPP()));
        RecalculaTotalBoton(0);        
    }
    
