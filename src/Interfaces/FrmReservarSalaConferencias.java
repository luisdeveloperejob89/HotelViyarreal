    public boolean ValidaDatosInsertados()
    {
        boolean bOk = true;
        
        if ( scSala.FechaReservada(this.scSala.getFechaReservada()) )
        {
            //Verificar la hora para ver si no chocan.
            if ( scSala.ChoqueDeHoraReservada(dtFechaReservacion.getDate(), txtHoraReservacion.getTimeField().getText(), Integer.parseInt(txtTiempoReservado.getText())) )
            {
                bOk = false;
            }
        }        
        
        return bOk;
    }
