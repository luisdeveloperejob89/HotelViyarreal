    public void InstanciaDatos()
    {
        double dTotalAnticipo = 0.0;
        double dDescuento = 0.0;
        double dTotal = 0.0;
        
        scSala.setNombre(txtNombre.getText());
        scSala.setPaquete(pPaquete.getID());
        scSala.setFechaReservada(dtFechaReservacion.getDate());
        scSala.setHoraReservada(txtHoraReservacion.getTimeField().getText());
        scSala.setTiempoReservado(Integer.parseInt(txtTiempoReservado.getText()));
        scSala.setAnticipo(cboxAnticipo.isSelected() ? 1 : 0);
                            
        if ( cboxAnticipo.isSelected() )
        {
            dTotalAnticipo = 0.0;
                                
            if ( !txtAnticipo.getText().isEmpty()  )
            {
                dTotalAnticipo = Double.parseDouble(txtAnticipo.getText());
            }
        }
                            
        scSala.setTotalAnticipo(dTotalAnticipo);                            
        dTotal = 0.0;
                            
        if ( !txtTotal.getText().isEmpty() )
        {
            dTotal = Double.parseDouble(txtTotal.getText());
        }
                            
        scSala.setTotal(dTotal);
        scSala.setCantPersonas(Integer.parseInt(txtTotalPersonas.getText()));                            
                            
        if ( cboxDescuentoEmpresas.isSelected() )
        {
            dDescuento = 0.0;
                                
            if ( !txtDescuento.getText().isEmpty() )
            {
                dDescuento = Double.parseDouble(txtDescuento.getText());
            }
                                
            scSala.setEmpresa(this.Empresa);
        }
                            
        scSala.setTotDescuento(dDescuento);
        scSala.setSaldo(dTotal - dTotalAnticipo);
    }
    
    public void ReservarSalaDeConferencias()
    {                
        if ( DatosClienteLlenos() )
        {
            if ( CamposReservacionLlenos() )
            {
                if ( PaqueteSeleccionado() )
                {
                    if ( DescuentoEmpresaLleno() )
                    {
                        if ( uAccesibilidad.MuestraMensajeConfirmacion("¿Realmente deseas agregar esta reservación?") == 0 )
                        {
                            InstanciaDatos();
                            
                            if ( ValidaDatosInsertados() )
                            {                            
                                if ( scSala.Insertar() )
                                {
                                    uAccesibilidad.MuestraMensaje("Se ha reservado correctamente la Sala de Conferencias.");
                                    this.dispose();
                                }
                                else
                                {
                                    uAccesibilidad.MuestraMensaje("Ocurrió un error al tratar de Insertar en la Base de Datos.");
                                }
                            }
                        }
                    }
                    else
                    {
                        uAccesibilidad.MuestraMensaje("Es necesario seleccionar una Empresa para aplicar Descuento.");
                    }
                }
                else
                {
                    uAccesibilidad.MuestraMensaje("Es necesario seleccionar un paquete para la Sala de Conferencias.");    
                }
            }
            else
            {
                uAccesibilidad.MuestraMensaje("Se debe seleccionar una fecha y/o una hora para la reservación.");
            }
        }
        else
        {
            uAccesibilidad.MuestraMensaje("Se debe capturar el Nombre o Razón Social.");
            txtNombre.requestFocus();
            txtNombre.selectAll();
        }                
    }
    
